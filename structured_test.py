"""Small capability test for block-routed SwiGLU.

The structured task is generated by reusable factors a and b. The random
control assigns each (a, b) pair an unrelated rule. Evaluation uses held-out
pairs whose individual factors were present during training.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

import torch
from torch import nn
import torch.nn.functional as F


@dataclass
class World:
    u: torch.Tensor
    w: torch.Tensor
    random_rules: torch.Tensor
    train_pairs: torch.Tensor
    heldout_pairs: torch.Tensor


def make_world(seed: int, categories: int, vdim: int, device: str) -> World:
    gen = torch.Generator(device=device).manual_seed(10_000 + seed)
    u = F.normalize(torch.randn(categories, vdim, generator=gen, device=device), dim=-1)
    w = F.normalize(torch.randn(categories, vdim, generator=gen, device=device), dim=-1)
    random_rules = F.normalize(
        torch.randn(categories, categories, vdim, generator=gen, device=device), dim=-1
    )
    pairs = torch.cartesian_prod(torch.arange(categories), torch.arange(categories))
    # Deterministic diagonal-like split: every a and every b remains in training.
    heldout_mask = ((pairs[:, 0] * 5 + pairs[:, 1] * 3 + seed) % 5) == 0
    return World(
        u, w, random_rules,
        pairs[~heldout_mask].to(device), pairs[heldout_mask].to(device),
    )


def sample(world: World, pair_set: torch.Tensor, batch: int, task: str,
           generator: torch.Generator) -> tuple[torch.Tensor, ...]:
    choice = torch.randint(len(pair_set), (batch,), generator=generator, device=pair_set.device)
    pair = pair_set[choice]
    a, b = pair[:, 0], pair[:, 1]
    v = torch.randn(batch, world.u.shape[1], generator=generator, device=pair_set.device)
    if task == "structured":
        score = (world.u[a] * v).sum(-1) * (world.w[b] * v).sum(-1)
    elif task == "random":
        score = (world.random_rules[a, b] * v).sum(-1)
    else:
        raise ValueError(task)
    return world.u[a], world.w[b], v, (score > 0).float()


class PairModel(nn.Module):
    def __init__(self, vdim: int, routed: bool):
        super().__init__()
        self.routed = routed
        self.block, self.width, self.blocks = 8, 128, 16
        self.in_proj = nn.Linear(3 * vdim, 64)
        self.gate_up = nn.Linear(64, 2 * self.width)
        self.router = nn.Linear(64, self.blocks * 4)
        self.down = nn.Linear(self.width, 64)
        self.out = nn.Linear(64, 1)
        lanes = torch.arange(self.block)
        self.register_buffer("perms", torch.stack((
            lanes, (lanes + 1) % self.block, lanes ^ 1, (lanes + 2) % self.block,
        )))

    def forward(self, a_factor: torch.Tensor, b_factor: torch.Tensor, v: torch.Tensor,
                hard: bool = False) -> torch.Tensor:
        h = F.silu(self.in_proj(torch.cat((a_factor, b_factor, v), dim=-1)))
        gate, up = self.gate_up(h).chunk(2, dim=-1)
        gate = gate.view(-1, self.blocks, self.block)
        up = up.view(-1, self.blocks, self.block)
        logits = self.router(h).view(-1, self.blocks, 4)
        candidates = gate[:, :, self.perms]
        if self.routed:
            soft_weights = F.softmax(logits, dim=-1)
            hard_weights = F.one_hot(logits.argmax(-1), 4).to(soft_weights.dtype)
            weights = hard_weights if hard else hard_weights - soft_weights.detach() + soft_weights
            paired_gate = (candidates * weights.unsqueeze(-1)).sum(2)
        else:
            # Router is intentionally present and evaluated for parameter fairness.
            paired_gate = candidates[:, :, 0] + logits.sum() * 0.0
        z = F.silu(paired_gate) * up
        return self.out(F.silu(self.down(z.flatten(1)))).squeeze(-1)


@torch.no_grad()
def evaluate(model: PairModel, world: World, pairs: torch.Tensor, task: str,
             generator: torch.Generator, batches: int = 20) -> float:
    model.eval()
    correct = total = 0
    for _ in range(batches):
        a_factor, b_factor, v, y = sample(world, pairs, 1024, task, generator)
        pred = model(a_factor, b_factor, v, hard=model.routed) > 0
        correct += (pred == y.bool()).sum().item()
        total += y.numel()
    return correct / total


def train_one(seed: int, task: str, routed: bool, steps: int, device: str) -> dict:
    torch.manual_seed(seed)
    world = make_world(seed, categories=16, vdim=16, device=device)
    model = PairModel(16, routed).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=2e-3, weight_decay=1e-4)
    train_gen = torch.Generator(device=device).manual_seed(20_000 + seed)
    for _ in range(steps):
        model.train()
        a_factor, b_factor, v, y = sample(world, world.train_pairs, 512, task, train_gen)
        loss = F.binary_cross_entropy_with_logits(model(a_factor, b_factor, v), y)
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
    eval_gen = torch.Generator(device=device).manual_seed(30_000 + seed)
    return {
        "seed": seed,
        "task": task,
        "model": "routed" if routed else "baseline",
        "parameters": sum(p.numel() for p in model.parameters()),
        "train_pairs_accuracy": evaluate(model, world, world.train_pairs, task, eval_gen),
        "heldout_pairs_accuracy": evaluate(model, world, world.heldout_pairs, task, eval_gen),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument("--steps", type=int, default=1500)
    parser.add_argument("--output", default="structured_results.json")
    args = parser.parse_args()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    results = []
    for task in ("structured", "random"):
        for seed in range(args.seeds):
            for routed in (False, True):
                result = train_one(seed, task, routed, args.steps, device)
                results.append(result)
                print(json.dumps(result), flush=True)
    Path(args.output).write_text(json.dumps(results, indent=2) + "\n")


if __name__ == "__main__":
    main()
